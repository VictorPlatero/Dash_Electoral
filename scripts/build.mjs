import { mkdir, cp, readFile, readdir, writeFile } from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {validateBatch} from '../src/schema.mjs';
import {fetchPublishedCuts,mergeHistory,readHistory,serializeHistory} from './history.mjs';
const catalog=JSON.parse(await readFile('public/candidates.json','utf8'));
validateBatch(catalog);
const localCuts=await readHistory();
const {SUPABASE_URL:url,SUPABASE_PUBLISHABLE_KEY:key}=process.env;
if(Boolean(url)!==Boolean(key))throw new Error('Configura SUPABASE_URL y SUPABASE_PUBLISHABLE_KEY juntas para el historial.');
const cuts=url ? mergeHistory(localCuts,await fetchPublishedCuts(url,key)) : localCuts;
await mkdir('dist', { recursive: true });
await cp('public', 'dist', { recursive: true, filter: path => !path.endsWith('.tmp') });
await writeFile('dist/electoral-history.json',serializeHistory(cuts));
const hash=createHash('sha256');
const assets=new Set([...await readdir('public'),'electoral-history.json']);
for(const path of [...assets].filter(path=>/\.(js|css|json|html)$/.test(path)).sort()) hash.update(path).update((await readFile('dist/'+path,'utf8')).replace(/\r\n/g,'\n'));
const version=JSON.parse(await readFile('package.json','utf8')).version;
await writeFile('dist/build-info.json',JSON.stringify({version,fingerprint:hash.digest('hex'),builtAt:new Date().toISOString(),candidates:catalog.candidates.length,cuts:cuts.length})+'\n');
console.log('Dashboard preparado en dist/');
